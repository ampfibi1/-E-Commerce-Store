    <h2>I'm a customer — how do I order?</h2>
    <p>Browse products, add items to your cart, then click <b>Checkout</b>. You'll choose a delivery zone, enter your shipping address, pick a payment method, and confirm your order. After ordering, track its status from <b>My Orders</b>.</p>

    <h2>I'm a seller — how do I list a product?</h2>
    <p>Once your seller account is approved by the admin, log in and open the <b>Seller Dashboard</b>. Click <b>Add New Product</b>, fill in the details (name, description, price, stock, category) and upload a primary image. Your product appears in the marketplace immediately.</p>

    <h2>How do I apply a coupon?</h2>
    <p>Enter the coupon code on the checkout page and click <b>Apply</b>. The discount will be deducted from your subtotal before payment.</p>

    <h2>What if my order arrives damaged?</h2>
    <p>Open <b>Order Detail</b> for that order, click <b>Request Return</b>, and describe the issue. You can also open a formal <b>Dispute</b> for admin review from the same page.</p>

